public class oneToHundred{
    public static void main(String[] args){

    for(int count = 1; count <= 100; count++){

        if(count % 3 == 0){

            System.out.println("hello");
        }
        else if(count % 5 == 0){
            System.out.println("World");
        }

        else if(count % 7 == 0){
            System.out.println("Orion");
        }else{
            System.out.println(count);
    }
        }
    }
    }
